// uncallableVerdicts are addresses of a server that can't be called
// (spec/v0/core.md section 5.2).
func uncallableVerdicts() []verdict {
	good := addrBPrivate
	mid := good[len("https://msfp-") : len(good)-len(".invalid")]
	list := []string{
		good,
		uncallableAddress(make([]byte, 16)),
		uncallableAddress(seq(0xf0, 16)),
		"https://msfp-" + strings.ToUpper(mid) + ".invalid",
		"https://msfp-" + mid[:25] + ".invalid",
		"https://msfp-" + mid + "a.invalid",
		"https://msfp-" + mid[:25] + "b.invalid",
		"https://msfp-" + mid[:25] + "1.invalid",
		"https://msfp-" + mid + ".invalid:8443",
		"https://msfp-" + mid + ".example.org",
		"https://" + mid + ".invalid",
		"https://x.msfp-" + mid + ".invalid",
		"https://msfp-" + mid + ".invalid.",
		"http://msfp-" + mid + ".invalid",
		"https://a.example.org",
		"https://192.0.2.10:8096",
	}
	var out []verdict
	for _, a := range list {
		ok, r := reason(checkUncallableAddress(a))
		out = append(out, verdict{Text: a, Valid: ok, Reason: r})
	}
	return out
}

// baseVerdicts are discovery documents' base paths (spec/v0/core.md).
func baseVerdicts() []verdict {
	var out []verdict
	for _, b := range []string{"/api/v1/federation/", "/srv/media/api/v1/federation/", "/a.b/~c/api/v1/federation/",
		"/srv/../api/v1/federation/", "/./api/v1/federation/", "/srv/./media/api/v1/federation/", "/srv//api/v1/federation/",
		"/srv%2Fmedia/api/v1/federation/", "/srv%2e%2e/api/v1/federation/", "srv/api/v1/federation/", "/api/v1/federation",
		"/api/v2/federation/", "/" + strings.Repeat("a", 240) + "/api/v1/federation/"} {
		ok, r := reason(checkBase(b))
		out = append(out, verdict{Text: b, Valid: ok, Reason: r})
	}
	return out
}

