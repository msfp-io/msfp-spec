// rotationStatement is core.md section 12.2's statement.
func rotationStatement(old, nu []byte, next string, date int64) string {
	if next == "" {
		next = "-"
	}
	return "msfp-key-rotation-1\n" + b64.EncodeToString(old) + "\n" + b64.EncodeToString(nu) + "\n" + next + "\n" + strconv.FormatInt(date, 10)
}

func revocationStatement(k []byte, date int64) string {
	return "msfp-key-revocation-1\n" + b64.EncodeToString(k) + "\n" + strconv.FormatInt(date, 10)
}

