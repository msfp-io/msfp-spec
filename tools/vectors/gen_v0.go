func genV0Keys() []byte {
	k := func(x key) v1Key {
		return v1Key{hex.EncodeToString(x.seed), x.text(), fingerprint(x.pub), commitment(x.pub)}
	}
	c := func(x key) v1Cert { return v1Cert{hex.EncodeToString(x.seed), hex.EncodeToString(spki(x)), pin(x)} }
	return encode(v1KeysFile{
		About: []string{
			"MSFP core version 0 test keys (spec/v0/core.md section 17). Generated by tools/vectors; no implementation has produced them yet.",
			"seed: the 32-byte Ed25519 seed of RFC 8032, hex. commitment: the next key commitment to that key, base64url of SHA-256 of its 32 bytes (core.md section 12).",
			"a and b are the test draft's keys. a2 and a3 are server A's next keys; b2 is server B's.",
			"certificates: Ed25519 keys of the servers' TLS certificates. spki: the DER SubjectPublicKeyInfo, hex. pin: base64url of SHA-256 of spki (core.md section 3.2).",
		},
		Keys:         map[string]v1Key{"a": k(keyA), "a2": k(keyA2), "a3": k(keyA3), "b": k(keyB), "b2": k(keyB2)},
		Certificates: map[string]v1Cert{"a": c(certA), "b": c(certB)},
	})
}

