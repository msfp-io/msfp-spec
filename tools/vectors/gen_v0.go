type v1Exchange struct {
	Name              string `json:"name"`
	Signer            string `json:"signer"`
	Answerer          string `json:"answerer"`
	Method            string `json:"method"`
	Host              string `json:"host"`
	Target            string `json:"target"`
	Date              string `json:"date"`
	Nonce             string `json:"nonce"`
	NonceText         string `json:"nonceText"`
	Body              string `json:"body"`
	Message           string `json:"message"`
	Signature         string `json:"signature"`
	Status            int    `json:"status"`
	AnswerContentType string `json:"answerContentType"`
	AnswerBody        string `json:"answerBody"`
	AnswerMessage     string `json:"answerMessage"`
	AnswerSignature   string `json:"answerSignature"`
}

func v1Exch(name, signer, answerer, host, target, date string, nonce []byte, body string, status int, ct, answerBody string) v1Exchange {
	s, a := testKeys[signer], testKeys[answerer]
	nt := b64.EncodeToString(nonce)
	msg := core0.requestMessage("POST", host, target, date, nt, body)
	am := core0.answerMessage(nt, status, ct, answerBody)
	return v1Exchange{name, signer, answerer, "POST", host, target, date, hex.EncodeToString(nonce), nt,
		body, msg, s.sign(msg), status, ct, answerBody, am, a.sign(am)}
}

type v1ExchangesFile struct {
	About     []string     `json:"about"`
	Exchanges []v1Exchange `json:"exchanges"`
}

const (
	ctJSON    = "application/json"
	ctProblem = "application/problem+json"
	hostA     = "a.example.org"
	hostB     = "192.0.2.10:8096"
	fed       = "/api/v1/federation/"
)

func v1PairBody() string {
	secret := mustHex(secretS)
	return fmt.Sprintf(`{"address":%q,"name":"Server B","secretHash":%q,"proof":%q,"nextCommitment":%q}`,
		addrBc, b64.EncodeToString(sha(secret)), core0.proof(secret, keyB.pub, addrBc), commitment(keyB2.pub))
}

func v1HelloBody() string {
	return fmt.Sprintf(`{"state":"paired","core":[0],"parts":{"catalog":[0],"playback":[0],"media":[0],"video":[0]},"certificates":[%q],"address":%q}`,
		pin(certA), addrA)
}

// v1PrivateHello is a hello from server B once it can't be called
// (spec/v0/core.md section 7.5): its address of section 5.2's form,
// inbound false, no pins, and the key it checks A's answers against.
func v1PrivateHello(known key) string {
	return fmt.Sprintf(`{"state":"paired","core":[0],"parts":{"catalog":[0],"playback":[0],"media":[0],"video":[0]},"address":%q,"inbound":false,"knownKey":%q}`,
		addrBPrivate, known.text())
}

// v1AHelloAnswer is A's answer to a hello, with extra members appended.
func v1AHelloAnswer(extra string) string {
	return fmt.Sprintf(`{"state":"paired","core":[0],"parts":{"catalog":[0],"playback":[0],"media":[0],"video":[0]},"certificates":[%q],"address":%q%s}`,
		pin(certA), addrA, extra)
}

// The pulled rotation and revocation (spec/v0/core.md sections 12.4 and
// 12.6): A revokes a and rotates to a2, committing to a3, in one action;
// its hello answer to B carries both statements, dated as it answers.
const pulledDate = 1800300000

func v1PulledMembers() string {
	rs := rotationStatement(keyA.pub, keyA2.pub, commitment(keyA3.pub), pulledDate)
	vs := revocationStatement(keyA.pub, pulledDate)
	return fmt.Sprintf(`,"rotation":{"newKey":%q,"nextCommitment":%q,"date":%d,"oldSignature":%q,"newSignature":%q},"revocation":{"date":%d,"signature":%q}`,
		keyA2.text(), commitment(keyA3.pub), pulledDate, keyA.sign(rs), keyA2.sign(rs), pulledDate, keyA.sign(vs))
}

