func v1Exch(name, signer, answerer, host, target, date string, nonce []byte, body string, status int, ct, answerBody string) v1Exchange {
	s, a := testKeys[signer], testKeys[answerer]
	nt := b64.EncodeToString(nonce)
	msg := core0.requestMessage("POST", host, target, date, nt, body)
	am := core0.answerMessage(nt, status, ct, answerBody)
	return v1Exchange{name, signer, answerer, "POST", host, target, date, hex.EncodeToString(nonce), nt,
		body, msg, s.sign(msg), status, ct, answerBody, am, a.sign(am)}
}

