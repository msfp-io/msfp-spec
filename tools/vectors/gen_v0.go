func genV0Rotation() []byte {
	const date = 1800100000
	st := rotationStatement(keyA.pub, keyA2.pub, commitment(keyA3.pub), date)
	r := rotation{"a", "a2", "a3", keyA.text(), keyA2.text(), commitment(keyA3.pub), date, st, keyA.sign(st), keyA2.sign(st)}
	body := fmt.Sprintf(`{"newKey":%q,"nextCommitment":%q,"date":%d,"oldSignature":%q,"newSignature":%q}`,
		r.NewKey, r.NextCommitment, date, r.OldSignature, r.NewSignature)
	return encode(rotationFile{
		About: []string{
			"Server A rotates from key a to key a2, committing to a3 as the key after a2 (spec/v0/core.md section 12). Generated by tools/vectors; no implementation has produced them yet.",
			"The statement is signed with the old key (oldSignature) and the new one (newSignature). The rotate request is signed with the old key, a; server B answers that a2 is now current.",
			"Server B holds the commitment to a2 (keys.json, a2's commitment, sent in A's pair answer), so the rotation takes effect at once.",
		},
		Rotation: r,
		Exchange: v1Exch("rotate", "a", "b", hostB, fed+"rotate", strconv.Itoa(date), seq(0xa0, 16), body, 200, ctJSON, `{"state":"rotated"}`),
	})
}

