// Core version 0's test keys: a and b as in the test draft; a2 and a3 are
// server A's next keys, b2 server B's.
var (
	keyA2 = newKey(seq(0x80, 32))
	keyA3 = newKey(seq(0xa0, 32))
	keyB2 = newKey(seq(0xc0, 32))
	// The keys of the servers' TLS certificates, kept apart from their
	// federation keys. Their seeds are SHA-256 of an ASCII text.
	certA = newKey(sha([]byte("msfp-spec certificate key a")))
	certB = newKey(sha([]byte("msfp-spec certificate key b")))
)

const addrBc = "https://192.0.2.10:8096" // server B in core 0

